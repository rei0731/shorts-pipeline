"""睡眠用ロングの題・説明・タグ（全ビルダー共通の唯一の出どころ）。

2026-09-03 に検索型へ移行した。それまでは
    【睡眠用】旅と道の物語｜古代の街道から夜汽車まで【約70分】
のように、先頭が括弧・主役が作品名で、「聞き流し」も「眠れない夜」も入っていなかった。
尺表記も「約70分」で、実際に打たれる「1時間」に当たらない。3時間版・5時間版に
至っては尺表記そのものが無かった。

channel B の勝ち動画（睡眠用ロング・1002回）と
channel A の睡眠用（最高72回）を比べたとき、差が出ていたのは中身ではなくここだった。
channel Cで 2026-09-01 に採った型をそのまま持ってきている。

効果が出るのは検索が育つ1〜3ヶ月後。すぐには数字は動かない。
"""


def sleep_title(hours: int, topic: str) -> str:
    """尺は実尺から切り下げる。1時間10分でも「1時間」（検索語がそれ）。"""
    return f"眠れない夜に都市伝説聞き流し{hours}時間｜{topic}【睡眠用・朗読】"


def sleep_desc(hours: int, lead: str, hashtags: str) -> str:
    return (f"都市伝説と世界の言い伝えを、ゆったりと約{hours}時間、聞き流しでお届けします。\n"
            f"眠れない夜の入眠用や、作業中の聞き流しにどうぞ。\n\n"
            f"{lead}\n\n{hashtags}")


HASHTAGS = "#睡眠用 #睡眠導入 #眠れない夜 #聞き流し #朗読 #作業用BGM"

# 睡眠系の検索意図をひととおり覆う共通タグ。題材ごとの語は sleep_tags() で足す。
# 旧タグにあった「怖い話」は睡眠用としては逆向きなので入れない。
SLEEP_TAGS_BASE = [
    "睡眠用", "睡眠導入", "眠れない夜", "聞き流し", "朗読", "作業用", "作業用BGM",
    "安眠", "快眠", "入眠", "寝落ち", "寝る前", "就寝前", "深夜", "夜のルーティン",
    "眠くなる", "癒し", "リラックス", "落ち着く", "長時間", "総集編",
    "ナレーション", "低音ボイス", "男性の声", "音声コンテンツ",
    "都市伝説", "ミステリー", "不思議な話", "眠れる話",
]


def sleep_tags(extra=()) -> list:
    """共通タグ＋題材タグ。YouTubeの上限500文字に収まるところまで。"""
    out, n = [], 0
    for t in list(SLEEP_TAGS_BASE) + list(extra):
        if t in out:
            continue
        n += len(t) + 1
        if n > 480:
            break
        out.append(t)
    return out
